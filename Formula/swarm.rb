class Swarm < Formula
  include Language::Python::Virtualenv

  desc "Autonomous LLM-based agent for automated web-application analysis"
  homepage "https://github.com/Joloooo/swarm"
  url "https://github.com/Joloooo/swarm/archive/refs/tags/v0.1.1.tar.gz"
  sha256 "4cea80c63367d38ced5e8d3d428a5e225a4e4377653949dbe2d04346caef275a"
  license "MIT"
  head "https://github.com/Joloooo/swarm.git", branch: "main"

  bottle do
    root_url "https://github.com/Joloooo/homebrew-swarm/releases/download/swarm-0.1.1"
    sha256 arm64_tahoe: "f67cbc0447970960831a622d7637d274a8f6f53968cc0247941d8854a3747083"
  end

  depends_on "nmap"
  depends_on "python@3.12"
  depends_on "tmux"

  def install
    # swarm's dependency tree (langchain, langgraph, pydantic, playwright,
    # reportlab, ...) is far too large to vendor as Homebrew resources, and
    # the built-in virtualenv helpers force --no-deps/--no-binary (source
    # builds), which breaks on playwright and the Rust-backed wheels. Instead
    # we build a plain venv and install the EXACT, hash-pinned dependency set
    # from requirements.lock.txt (generated by `uv export` from uv.lock), so
    # every install resolves to identical versions. The package itself is then
    # installed with --no-deps on top.
    system formula_opt_bin("python@3.12")/"python3.12", "-m", "venv", libexec
    system libexec/"bin/pip", "install", "--no-cache-dir",
           "--requirement", buildpath/"requirements.lock.txt"
    system libexec/"bin/pip", "install", "--no-cache-dir", "--no-deps", buildpath
    bin.install_symlink libexec/"bin/swarm"
    bin.install_symlink libexec/"bin/swarmattacker"
  end

  def caveats
    <<~EOS
      swarm drives a headless browser via Playwright. Install the Chromium
      runtime once with:
        #{libexec}/bin/playwright install chromium

      Directory/credential brute-forcing tools use SecLists when present.
      Install the wordlists (optional, only for deep fuzzing) into
      ~/.swarmattacker/seclists, or install additional pentest binaries:
        brew install gobuster sqlmap nikto

      Set your LLM provider key before running, e.g.:
        export ANTHROPIC_API_KEY=...   # or OPENAI_API_KEY=...
    EOS
  end

  test do
    assert_match(/swarm|usage|Usage/i, shell_output("#{bin}/swarm --help 2>&1"))
  end
end
